
numero = int(input("Digite um número: "))

dobro = int(numero + numero)
triplo = int(numero + numero + numero)
quadrado = int(numero ** 2)
raiz_quadrada = int(numero ** (1/2))
raiz_cubica = int(numero ** (1/3))

print(f"O dobro do número é: {dobro}")
print(f"O triplo do número é: {triplo}")
print(f"O número ao quadrado é: {quadrado}")
print(f"A raiz quadrada é: {raiz_quadrada}")
print(f"A raiz cúbica é: {raiz_cubica}")
